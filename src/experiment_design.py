"""
experiment_design.py
Demonstrates experimentation/A-B-testing skills the way a Data Scientist would
use them before a real promo is launched. This module does NOT claim a real
Yum/Maven Roasters promotion happened - it is explicitly a SIMULATION built on
top of the real per-transaction revenue distribution observed in the dataset.

Two things are produced:
1. A power analysis: given the *actual* observed mean/std of transaction
   revenue, how many transactions per arm would a promo experiment need to
   reliably detect a stated uplift?
2. A simulated 2-week A/B test: a synthetic "treatment" group is generated by
   resampling real transactions and adding an ASSUMED uplift (stated
   explicitly), then analyzed with a two-sample t-test exactly as a real
   experiment would be. All uplift numbers here are assumptions for
   demonstration, not measured business results.
"""
import numpy as np
import pandas as pd
from scipy import stats
from statsmodels.stats.power import TTestIndPower

ASSUMED_UPLIFT_PCT = 0.05  # 5% assumed lift in average transaction revenue - ASSUMPTION, not observed


def required_sample_size(mean: float, std: float, uplift_pct: float = ASSUMED_UPLIFT_PCT,
                          alpha: float = 0.05, power: float = 0.8) -> dict:
    effect_size = (mean * uplift_pct) / std  # Cohen's d for a mean-shift alternative
    analysis = TTestIndPower()
    n_per_group = analysis.solve_power(effect_size=effect_size, alpha=alpha, power=power,
                                        ratio=1.0, alternative="two-sided")
    return {
        "baseline_mean_revenue": round(mean, 4),
        "baseline_std_revenue": round(std, 4),
        "assumed_uplift_pct": uplift_pct,
        "cohens_d": round(effect_size, 4),
        "alpha": alpha, "power": power,
        "required_n_per_arm": int(np.ceil(n_per_group)),
    }


def simulate_ab_test(real_revenue: pd.Series, uplift_pct: float = ASSUMED_UPLIFT_PCT,
                      n_per_arm: int = 4000, seed: int = 42) -> dict:
    rng = np.random.default_rng(seed)
    control = rng.choice(real_revenue.values, size=n_per_arm, replace=True)
    treatment_base = rng.choice(real_revenue.values, size=n_per_arm, replace=True)
    treatment = treatment_base * (1 + uplift_pct)  # assumed uplift injected for simulation

    t_stat, p_val = stats.ttest_ind(treatment, control, equal_var=False)
    observed_lift = (treatment.mean() - control.mean()) / control.mean() * 100
    ci_low, ci_high = stats.norm.interval(0.95, loc=treatment.mean() - control.mean(),
                                           scale=np.sqrt(treatment.var(ddof=1) / n_per_arm + control.var(ddof=1) / n_per_arm))
    return {
        "note": "SIMULATED experiment - uplift was injected, not observed in real Maven Roasters/Yum data.",
        "n_per_arm": n_per_arm,
        "control_mean": round(control.mean(), 4),
        "treatment_mean": round(treatment.mean(), 4),
        "observed_lift_pct": round(observed_lift, 2),
        "t_stat": round(t_stat, 4), "p_value": p_val,
        "95pct_ci_diff": (round(ci_low, 4), round(ci_high, 4)),
        "significant_at_0.05": bool(p_val < 0.05),
    }


def run(df: pd.DataFrame) -> dict:
    revenue = df.groupby("transaction_id")["revenue"].sum() if "transaction_id" in df.columns else df["revenue"]
    power_result = required_sample_size(revenue.mean(), revenue.std())
    ab_result = simulate_ab_test(revenue)
    return {"power_analysis": power_result, "simulated_ab_test": ab_result}


